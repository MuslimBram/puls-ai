export const PUBLIC_PRODUCT_REGISTRY: PublicProductFeature[] = [
  ...BASE_PUBLIC_PRODUCT_REGISTRY.map((feature) => ({
    ...feature,
    ...(PUBLIC_ROUTE_OVERRIDES[feature.key] ?? {}),
  })),
  ...EXTRA_PUBLIC_PRODUCT_FEATURES,
];

export function findPublicProductFeatures(question: string, maxResults = 6): PublicProductFeature[] {
  const normalized = question.toLowerCase();
  const scored = PUBLIC_PRODUCT_REGISTRY.map((feature) => {
    let score = 0;
    for (const term of [...feature.names, ...feature.keywords]) {
      const needle = term.toLowerCase();
      if (!needle) continue;
      if (normalized.includes(needle)) score += needle.length >= 8 ? 3 : 1;
    }
    return { feature, score };
  })
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, Math.max(1, Math.min(maxResults, 10))).map(({ feature }) => feature);
}
