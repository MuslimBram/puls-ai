export function publicProductContext(): string {
  return JSON.stringify(
    PUBLIC_PRODUCT_REGISTRY.map((feature) => ({
      key: feature.key,
      names: feature.names,
      summary_sq: feature.summary_sq,
      summary_en: feature.summary_en,
      how_it_works_sq: feature.how_it_works_sq,
      how_it_works_en: feature.how_it_works_en,
      benefit_sq: feature.benefit_sq,
      benefit_en: feature.benefit_en,
      route: feature.route,
      public_info_route: feature.public_info_route ?? feature.route,
      audience: feature.audience,
      status: feature.status,
      status_note_sq: feature.status_note_sq,
      status_note_en: feature.status_note_en,
    })),
  );
}

export function findPublicProductFeatures(question: string, maxResults = 4): PublicProductFeature[] {
  const normalized = question.toLowerCase();
  const scored = PUBLIC_PRODUCT_REGISTRY.map((feature) => {
    let score = 0;
    for (const term of [...feature.names, ...feature.keywords]) {
      const needle = term.toLowerCase();
      if (needle && normalized.includes(needle)) score += needle.length >= 8 ? 3 : 1;
    }
    return { feature, score };
  })
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score);

  return scored.slice(0, Math.max(1, Math.min(maxResults, 8))).map(({ feature }) => feature);
}
